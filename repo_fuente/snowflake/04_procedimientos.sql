-- Refresco por fecha: conservar particiones ajenas a p_date.
CREATE OR REPLACE PROCEDURE ANALYTICS.REFRESH_DAILY_SALES(p_date DATE)
RETURNS VARCHAR LANGUAGE SQL AS
$$
BEGIN
 BEGIN TRANSACTION;
 DELETE FROM ANALYTICS.DAILY_SALES WHERE SALES_DATE = :p_date;
 INSERT INTO ANALYTICS.DAILY_SALES
 SELECT ORDER_DATE, COUNT(*), SUM(NET_AMOUNT)
 FROM ANALYTICS.V_ORDERS WHERE ORDER_DATE = :p_date GROUP BY ORDER_DATE;
 COMMIT;
 RETURN 'ok';
EXCEPTION
 WHEN OTHER THEN
  ROLLBACK;
  RAISE;
END;
$$;
-- Uso manual: CALL ANALYTICS.REFRESH_DAILY_SALES('2025-01-03'::DATE);
