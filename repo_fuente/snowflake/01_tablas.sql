-- Ejecutar en una base de datos de laboratorio ya seleccionada.
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;
CREATE TABLE IF NOT EXISTS RAW.CUSTOMERS (
 CUSTOMER_ID NUMBER(18,0), EMAIL VARCHAR, UPDATED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS RAW.ORDERS (
 ORDER_ID NUMBER(18,0), CUSTOMER_ID NUMBER(18,0), ORDER_DATE DATE,
 AMOUNT NUMBER(12,2), DISCOUNT_PCT NUMBER(5,2), STATUS VARCHAR,
 UPDATED_AT TIMESTAMP_NTZ, METADATA VARIANT
);
CREATE TABLE IF NOT EXISTS ANALYTICS.DAILY_SALES (
 SALES_DATE DATE, ORDER_COUNT NUMBER, NET_REVENUE NUMBER(18,2)
);
